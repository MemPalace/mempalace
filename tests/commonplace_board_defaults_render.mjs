import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
const app = await readFile(new URL('../commonplace/web/static/app.js', import.meta.url), 'utf8');
const slice = (start, end) => app.slice(app.indexOf(start), app.indexOf(end, app.indexOf(start)));
const e = (value) => String(value ?? '').replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const nav = {}, phoneBar = {}, phoneTabs = {}, panel = { hidden: true }, requests = [];
const board = { slug: 'fresh-space', name: 'Fresh workspace', counts: {} };
const state = { me: { workspace: 'example', actor: 'user:one', people: {}, email: 'one@example.com' }, boards: [board], base: '#/board/fresh-space', needs: {}, rulesWaiting: 0, card: { number: 3, version: 1, body: 'Original <context>', status_line: '' } };
const root = { querySelector: (selector) => ({ '#board-nav': nav, '#phone-bar': phoneBar, '#phone-tabs': phoneTabs, '#card-panel': panel })[selector], querySelectorAll: () => [] };
const dataUrl = (text) => `data:text/javascript;base64,${Buffer.from(text).toString('base64')}`;
const apiUrl = dataUrl(await readFile(new URL('../commonplace/web/static/api.js', import.meta.url), 'utf8'));
const railSource = await readFile(new URL('../commonplace/web/static/rail.js', import.meta.url), 'utf8');
const rail = await import(dataUrl(railSource.replace("'./api.js'", JSON.stringify(apiUrl))));
for (const name of ['renderRail', 'renderPhoneBar', 'renderPhoneTabs']) assert.equal(typeof rail[name], 'function');
const context = { state, root, e, enc: encodeURIComponent, ...rail, currentBoard: () => board, needsCards: () => [] };
runInNewContext(slice('function navigation()', 'function showError') + '\nnavigation();', context);
assert.ok(nav.outerHTML.includes('href="#/board/fresh-space"'));
assert.ok(nav.outerHTML.includes('data-action="new-board"'));
assert.ok(!nav.outerHTML.includes('href="#/space/fresh-space"'));
assert.equal((phoneTabs.innerHTML.match(/<a /g) || []).length, 3);
runInNewContext(slice('function reviewForm()', 'function handoffForm(') + '\nreviewForm();', context);
assert.equal(panel.hidden, false);
assert.ok(panel.innerHTML.includes('name="question" minlength="24" required'));
assert.ok(panel.innerHTML.includes('name="context" minlength="20" required'));
assert.ok(panel.innerHTML.includes('Original &lt;context&gt;'));
assert.ok(panel.innerHTML.includes('name="options"'));
const submission = slice('else if (kind === "board")', 'else if (kind === "space-message")');
const body = submission.slice(submission.indexOf('await mutate'), submission.lastIndexOf(';') + 1);
const location = { hash: '' };
await runInNewContext(`(async () => { ${body} })()`, { root, location, enc: encodeURIComponent, payload: { name: 'Release planning' }, mutate: async (_key, work) => work(), api: async (url, options) => requests.push({ url, options }) });
assert.equal(requests[0].url, '/api/boards');
assert.deepEqual(JSON.parse(JSON.stringify(requests[0].options.body)), { name: 'Release planning', slug: 'release-planning' });
assert.equal(location.hash, '#/board/release-planning');
assert.equal(panel.hidden, true);
// Proposal decisions use the public API and the version shown, never a database write.
await runInNewContext(slice('async function approveProposal(', 'function clearDecisionDraft(') + '\napproveProposal(state.card.number, state.card.version, true);', { state, mutate: async (_key, work) => work(), api: async (url, options) => requests.push({ url, options }) });
assert.equal(requests[1].url, '/api/cards/3/approve');
assert.equal(requests[1].options.body.approve, true);
assert.equal(requests[1].options.body.version, 1);
