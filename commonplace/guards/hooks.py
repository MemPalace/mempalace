"""Install the shared git hooks: pre-commit through pre-commit, pre-push as a quick check.

Git hooks live in the clone's common hooks directory, so every linked worktree
runs the same file. The hook pre-commit writes bakes in one absolute interpreter
path (whichever worktree ran ``pre-commit install``) and otherwise needs
``pre-commit`` on PATH; in a fresh worktree both are missing and every commit
fails. The scripts written here look for the tools of the worktree they run in,
and when none are there they say how to set one up.

    python -m commonplace.guards.hooks install   # write both hooks
    python -m commonplace.guards.hooks status    # what each hook would use here
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

MARKER = "commonplace-managed git hook"
PRE_COMMIT_MARKER = "File generated by pre-commit"
# hook -> (module the interpreter must import, command line after ``python -m``)
HOOKS = {
    "pre-commit": (
        "pre_commit",
        "pre_commit hook-impl --config=.pre-commit-config.yaml"
        ' --hook-type=pre-commit --hook-dir "$HERE" -- "$@"',
    ),
    "pre-push": ("commonplace.guards.prepush", 'commonplace.guards.prepush "$@"'),
}

# Shared by both hooks; %(...)s fields are filled per hook.
_TEMPLATE = """#!/bin/sh
# %(marker)s: %(hook)s. Shared by every worktree of this clone; do not edit.
# Regenerate with: python -m commonplace.guards.hooks install
HOOK=%(hook)s
MODULE=%(module)s
HERE=$(cd "$(dirname "$0")" && pwd)
TOP=$(git rev-parse --show-toplevel 2>/dev/null) || {
    echo "commonplace $HOOK hook: not inside a work tree" >&2
    exit 1
}
cd "$TOP" || exit 1

# The worktree's own environment first, then an activated one, then PATH.
PY=
if [ -n "$COMMONPLACE_PYTHON" ]; then
    PY=$COMMONPLACE_PYTHON
elif [ -x "$TOP/.venv/bin/python" ]; then
    PY=$TOP/.venv/bin/python
elif [ -x "$TOP/.venv/Scripts/python.exe" ]; then
    PY=$TOP/.venv/Scripts/python.exe
elif [ -n "$VIRTUAL_ENV" ] && [ -x "$VIRTUAL_ENV/bin/python" ]; then
    PY=$VIRTUAL_ENV/bin/python
else
    PY=$(command -v python3 || command -v python)
fi

if [ -z "$PY" ] || ! "$PY" -c "import $MODULE" >/dev/null 2>&1; then
    cat >&2 <<EOF
commonplace $HOOK hook: no Python environment for this worktree has '$MODULE'.
  worktree: $TOP
  looked at: \\$COMMONPLACE_PYTHON, $TOP/.venv, \\$VIRTUAL_ENV, python3 on PATH
Set one up in this worktree:
  cd "$TOP" && uv sync --extra dev
or use an existing environment for this one command:
  COMMONPLACE_PYTHON=/path/to/python git ...
EOF
    exit 1
fi

exec "$PY" -m %(run)s
"""


def render(hook: str) -> str:
    module, run = HOOKS[hook]
    return _TEMPLATE % {"marker": MARKER, "hook": hook, "module": module, "run": run}


def hooks_dir(repo: str | os.PathLike[str]) -> Path:
    """The directory git reads hooks from for ``repo``, shared by all its worktrees."""
    proc = subprocess.run(
        [
            "git",
            "-C",
            os.fspath(repo),
            "rev-parse",
            "--path-format=absolute",
            "--git-path",
            "hooks",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(proc.stderr.strip() or "not a git repository")
    return Path(proc.stdout.strip())


@dataclass(frozen=True)
class InstallResult:
    hook: str
    path: Path
    action: str  # written, unchanged, replaced (a pre-commit generated one) or kept


def install(repo: str | os.PathLike[str], force: bool = False) -> list[InstallResult]:
    """Write both hooks. A hook this tool did not write is kept unless ``force``."""
    directory = hooks_dir(repo)
    directory.mkdir(parents=True, exist_ok=True)
    results = []
    for hook in HOOKS:
        path = directory / hook
        text = render(hook)
        action = "written"
        if path.exists():
            current = path.read_text(encoding="utf-8", errors="replace")
            if current == text:
                results.append(InstallResult(hook, path, "unchanged"))
                continue
            if MARKER in current:
                action = "written"
            elif PRE_COMMIT_MARKER in current:
                action = "replaced"
            elif force:
                shutil.copy2(path, path.with_name(f"{hook}.bak"))
                action = "replaced"
            else:
                results.append(InstallResult(hook, path, "kept"))
                continue
        path.write_text(text, encoding="utf-8")
        path.chmod(0o755)
        results.append(InstallResult(hook, path, action))
    return results


def status(repo: str | os.PathLike[str]) -> list[str]:
    """One line per hook: installed or not, and which interpreter it picks in ``repo``."""
    top = Path(
        subprocess.run(
            ["git", "-C", os.fspath(repo), "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    )
    own = next(
        (
            str(p)
            for p in (top / ".venv" / "bin" / "python", top / ".venv" / "Scripts" / "python.exe")
            if p.is_file()
        ),
        None,
    )
    env = own or os.environ.get("VIRTUAL_ENV") or shutil.which("python3") or "none"
    lines = []
    for hook in HOOKS:
        path = hooks_dir(repo) / hook
        if not path.exists():
            state = "not installed"
        elif MARKER in path.read_text(encoding="utf-8", errors="replace"):
            state = "installed"
        else:
            state = "present, not written by this tool (run install)"
        lines.append(f"{hook}: {state}")
    lines.append(
        f"worktree {top}: "
        + (f"uses {own}" if own else f"no .venv; would try {env} (run: uv sync --extra dev)")
    )
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m commonplace.guards.hooks", description="Install the shared git hooks."
    )
    sub = parser.add_subparsers(dest="command", required=True)
    one = sub.add_parser("install", help="write the pre-commit and pre-push hooks")
    one.add_argument(
        "--force", action="store_true", help="replace a hook of your own (kept as .bak)"
    )
    sub.add_parser("status", help="show what each hook would use in this worktree")
    args = parser.parse_args(argv)
    try:
        if args.command == "status":
            print("\n".join(status(".")))
            return 0
        results = install(".", args.force)
    except (RuntimeError, subprocess.CalledProcessError) as exc:
        print(f"hooks: {exc}", file=sys.stderr)
        return 2
    for result in results:
        print(f"{result.hook}: {result.action} ({result.path})")
    if any(result.action == "kept" for result in results):
        print("A hook of your own was kept; re-run with --force to replace it (saved as .bak).")
        return 1
    print("Each worktree needs its own environment: run `uv sync --extra dev` in it.")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
